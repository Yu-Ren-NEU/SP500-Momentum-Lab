export const formatMoney = (n: number | null, lang: Lang) =>
  n === null
    ? "—"
    : new Intl.NumberFormat(lang === "zh" ? "en-US" : "en-US", {
        style: "currency",
        currency: "USD",
        maximumFractionDigits: 2,
      }).format(n);
export const formatPct = (n: number | null) =>
  n === null ? "—" : `${(n * 100).toFixed(2)}%`;
